#!/usr/bin/env node
/*
 * Merges src/ (core + per-component html/js/css) and data/ into a static site in dist/:
 *   dist/index.html  – page shell + all component <template>s
 *   dist/app.css     – base styles + component styles
 *   dist/app.js      – sample data + core + components + bootstrap
 *   dist/data/       – copy of sample JSON (downloadable / importable)
 * Usage: node build.js [--watch]
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = __dirname;
const SRC = path.join(ROOT, 'src');
const DATA = path.join(ROOT, 'data');
const DIST = path.join(ROOT, 'dist');
const CORE_ORDER = ['utils.js', 'bus.js', 'validation.js', 'store.js'];

const read = (p) => fs.readFileSync(p, 'utf8');
const rel = (p) => path.relative(ROOT, p);
const banner = (p, body) => `/* ---- ${rel(p)} ---- */\n${body.trim()}\n`;

function components() {
  const dir = path.join(SRC, 'components');
  return fs.readdirSync(dir)
    .filter((name) => fs.statSync(path.join(dir, name)).isDirectory())
    .sort()
    .map((name) => {
      const base = path.join(dir, name, name);
      const files = { name };
      for (const ext of ['html', 'js', 'css']) {
        const f = `${base}.${ext}`;
        if (fs.existsSync(f)) files[ext] = f;
      }
      if (!files.js) throw new Error(`Component "${name}" is missing ${name}.js`);
      return files;
    });
}

function readJson(p) {
  try {
    return JSON.parse(read(p));
  } catch (err) {
    throw new Error(`Invalid JSON in ${rel(p)}: ${err.message}`);
  }
}

function sampleData() {
  const plansDir = path.join(DATA, 'plans');
  const plans = fs.existsSync(plansDir)
    ? fs.readdirSync(plansDir).filter((f) => f.endsWith('.json')).sort().map((f) => readJson(path.join(plansDir, f)))
    : [];
  return {
    courses: readJson(path.join(DATA, 'courses.json')),
    universities: readJson(path.join(DATA, 'universities.json')),
    plans,
  };
}

function checkSampleData(data) {
  const ids = new Set(data.courses.map((c) => c.id));
  const problems = [];
  for (const u of data.universities) {
    u.courses.filter((id) => !ids.has(id)).forEach((id) => problems.push(`${u.universityId}: unknown course ${id}`));
  }
  for (const p of data.plans) {
    p.courseList.filter((e) => !ids.has(e.courseId)).forEach((e) => problems.push(`${p.planId}: unknown course ${e.courseId}`));
  }
  problems.forEach((m) => console.warn(`  ⚠ ${m}`));
}

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const s = path.join(from, entry.name);
    const d = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
  }
}

function build() {
  const started = Date.now();
  const comps = components();
  const data = sampleData();
  checkSampleData(data);

  const css = [path.join(SRC, 'styles', 'base.css'), ...comps.filter((c) => c.css).map((c) => c.css)]
    .map((f) => banner(f, read(f))).join('\n');

  const js = [
    '/* Generated by build.js — do not edit. */',
    `window.SAMPLE_DATA = ${JSON.stringify(data)};`,
    ...CORE_ORDER.map((f) => path.join(SRC, 'core', f)).map((f) => banner(f, read(f))),
    ...comps.map((c) => banner(c.js, read(c.js))),
    banner(path.join(SRC, 'app.js'), read(path.join(SRC, 'app.js'))),
  ].join('\n');

  const templates = comps.filter((c) => c.html).map((c) => `<!-- ${c.name} -->\n${read(c.html).trim()}`).join('\n');
  const hash = crypto.createHash('sha1').update(css + js + templates).digest('hex').slice(0, 10);
  const html = read(path.join(SRC, 'index.html'))
    .replace('<!-- @templates -->', templates)
    .replace(/@buildHash/g, hash);

  fs.rmSync(DIST, { recursive: true, force: true });
  fs.mkdirSync(DIST, { recursive: true });
  fs.writeFileSync(path.join(DIST, 'index.html'), html);
  fs.writeFileSync(path.join(DIST, 'app.css'), css);
  fs.writeFileSync(path.join(DIST, 'app.js'), js);
  fs.writeFileSync(path.join(DIST, '.nojekyll'), '');
  copyDir(DATA, path.join(DIST, 'data'));

  console.log(`Built ${comps.length} components → ${rel(DIST)}/ (${hash}) in ${Date.now() - started}ms`);
}

function safeBuild() {
  try {
    build();
    return true;
  } catch (err) {
    console.error(`Build failed: ${err.message}`);
    return false;
  }
}

if (process.argv.includes('--watch')) {
  safeBuild();
  let timer = null;
  const onChange = () => { clearTimeout(timer); timer = setTimeout(safeBuild, 100); };
  [SRC, DATA].forEach((dir) => fs.watch(dir, { recursive: true }, onChange));
  console.log('Watching src/ and data/ for changes…');
} else if (!safeBuild()) {
  process.exit(1);
}
